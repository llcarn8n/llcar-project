    ax_shape1 INTEGER, ax_shape2 INTEGER, ax_shape3 INTEGER, ax_shape4 INTEGER,
    -- Y axis
    ay_min INTEGER, ay_max INTEGER, ay_avg INTEGER, ay_std INTEGER,
