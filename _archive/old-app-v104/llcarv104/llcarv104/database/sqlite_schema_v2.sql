    p010d INTEGER, p010e INTEGER, p010f INTEGER, p0111 INTEGER,
    p0113 INTEGER, p0114 INTEGER, p0115 INTEGER, p011f INTEGER,
    p0121 INTEGER, p0123 INTEGER, p012e INTEGER, p012f INTEGER,
    p0130 INTEGER, p0131 INTEGER, p0132 INTEGER, p0134 INTEGER,
    p013c INTEGER, p0141 INTEGER, p0142 INTEGER, p0143 INTEGER,
    p0144 INTEGER, p0145 INTEGER, p0146 INTEGER, p0147 INTEGER,
    p014c INTEGER, p014d INTEGER, p0151 INTEGER, p0155 INTEGER,
    p0162 INTEGER, p0163 INTEGER, p0187 INTEGER, p019e INTEGER,
    p01a6 INTEGER,
    -- 10 extended fields
    ext_01 INTEGER, ext_02 INTEGER, ext_03 INTEGER, ext_04 INTEGER,
    ext_05 INTEGER, ext_06 INTEGER, ext_07 INTEGER, ext_08 INTEGER,
    ext_09 INTEGER, ext_10 INTEGER,
    PRIMARY KEY (packet_id)
