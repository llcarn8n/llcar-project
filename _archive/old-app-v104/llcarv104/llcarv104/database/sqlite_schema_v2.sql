-- SQLite schema for llcar app (normalized structure)
-- 11 tables: 1 main + 8 ECU + 2 sensor tables
-- Created: 2026-03-18

-- Main packet table
CREATE TABLE IF NOT EXISTS qtp_packets (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    time INTEGER,                    -- Unix timestamp ms
    client_hash TEXT,
    geo_hash TEXT,
    road_type TEXT,
    season TEXT,
    acceleration_state TEXT,
    weather_temp REAL,
    weather_humidity INTEGER,
    weather_wind REAL,
    weather_condition TEXT,
    device_battery INTEGER,
    device_charging INTEGER,
    duration_ms INTEGER,
    ecu_mask INTEGER DEFAULT 0,      -- Bitmask of active ECUs (bit 0=7E8, bit 1=7E9, etc.)
    upload_status TEXT DEFAULT 'pending',  -- pending/sent/failed
    retry_count INTEGER DEFAULT 0,
    created_at INTEGER               -- Unix timestamp ms
);

-- Indexes for common queries
CREATE INDEX IF NOT EXISTS idx_packets_time ON qtp_packets(time DESC);
CREATE INDEX IF NOT EXISTS idx_packets_upload ON qtp_packets(upload_status, time);

-- ECU 7E8 table
CREATE TABLE IF NOT EXISTS ecu_7e8 (
    packet_id INTEGER REFERENCES qtp_packets(id) ON DELETE CASCADE,
    -- 40 standard PIDs
    p0103 INTEGER, p0104 INTEGER, p0105 INTEGER, p0106 INTEGER,
