-- Audio windows table
CREATE TABLE IF NOT EXISTS audio_windows (
    packet_id INTEGER REFERENCES qtp_packets(id) ON DELETE CASCADE,
    window_index INTEGER,
    -- 10 frequencies
    freq_1 INTEGER, amp_1 INTEGER, freq_2 INTEGER, amp_2 INTEGER,
    freq_3 INTEGER, amp_3 INTEGER, freq_4 INTEGER, amp_4 INTEGER,
    freq_5 INTEGER, amp_5 INTEGER, freq_6 INTEGER, amp_6 INTEGER,
    freq_7 INTEGER, amp_7 INTEGER, freq_8 INTEGER, amp_8 INTEGER,
    freq_9 INTEGER, amp_9 INTEGER, freq_10 INTEGER, amp_10 INTEGER,
    -- 10 peaks
    peak_1_offset INTEGER, peak_1_amp INTEGER, peak_2_offset INTEGER, peak_2_amp INTEGER,
    peak_3_offset INTEGER, peak_3_amp INTEGER, peak_4_offset INTEGER, peak_4_amp INTEGER,
    peak_5_offset INTEGER, peak_5_amp INTEGER, peak_6_offset INTEGER, peak_6_amp INTEGER,
    peak_7_offset INTEGER, peak_7_amp INTEGER, peak_8_offset INTEGER, peak_8_amp INTEGER,
    peak_9_offset INTEGER, peak_9_amp INTEGER, peak_10_offset INTEGER, peak_10_amp INTEGER,
    -- Audio quality score (0-100) for this 1-second window
    -- 100 = perfect vehicle sounds, 0 = heavily contaminated by music/speech
    quality INTEGER DEFAULT 50,
    PRIMARY KEY (packet_id, window_index)
);
